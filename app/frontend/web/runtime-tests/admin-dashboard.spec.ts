test('real masked shipment detail reads immutable Parcel identities and intake without private Customer data', async ({ page }) => {
  await login(page);
  await page.getByRole('button', { name: 'Đã tiếp nhận: 1 vận đơn' }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  const response = page.waitForResponse(r => /^\/api\/v1\/admin\/shipments\/[a-f0-9-]{36}$/.test(new URL(r.url()).pathname));
  await page.getByRole('button', { name: /^Xem chi tiết AP-SIM-/ }).click();
  const detail = await response; expect(detail.status()).toBe(200);
  const body = await detail.json(); expect(body.parcels).toHaveLength(3); expect(body.tracking).toHaveLength(1);
  expect(body.acceptance).not.toBeNull(); expect(body.shipment.status).toBe('AT_STATION');
  for (const field of ['recipient', 'sender', 'email', 'phone', 'password', 'proof']) expect(JSON.stringify(body).toLowerCase()).not.toContain(field);
  await expect(page.getByRole('columnheader', { name: 'Mã kiện' })).toBeVisible();
  await expect(page.locator('.ap-oversight tbody tr')).toHaveCount(3);
  await expect(page.locator('.ap-oversight-timeline')).toContainText('Carrier đã tiếp nhận tại');
  for (const parcel of body.parcels) await expect(page.getByRole('cell', { name: parcel.code, exact: true })).toBeVisible();
  await page.screenshot({ path: resolve(directory!, 'admin-oversight-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: resolve(directory!, 'admin-oversight-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Về danh sách vận đơn' }).click();
  await expect(page.getByRole('columnheader', { name: 'Mã vận đơn' })).toBeVisible();
  await expect(page.locator('tbody tr')).toHaveCount(1);
});
