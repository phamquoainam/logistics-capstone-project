import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
import { settings, evidencePath } from './support/settings';
async function login(page: Page, username: string, password: string) {
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Tên đăng nhập' }).fill(username);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Đăng nhập →' }).click();
}
test('merchant creates, reads, cancels; another merchant cannot read it', async ({ page, browser }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await login(page, 'demo.merchant.a', settings.merchantAPassword);
  await expect(page.getByRole('heading', { name: 'Merchant A · Demo' })).toBeVisible();
  await page.getByRole('link', { name: '＋ Tạo vận đơn nháp' }).first().click();
  const reference = `BROWSER-${Date.now()}`;
  await page.getByLabel('Mã tham chiếu').fill(reference);
  await page.getByLabel('Địa chỉ lấy hàng').fill('Điểm gửi demo · dữ liệu tổng hợp');
  await page.getByLabel('Tên người nhận').fill('Người nhận Demo');
  await page.getByLabel('Số điện thoại').fill('0000000000');
  await page.getByLabel('Số nhà, đường').fill('Địa chỉ demo chưa xác minh');
  await page.getByLabel('Phường / xã').fill('Phường demo');
  await page.getByLabel('Tỉnh / thành phố').fill('Thành phố demo');
  await page.getByLabel('Mô tả kiện hàng').fill('Tài liệu trình diễn');
  await page.getByLabel('Khối lượng (kg)').fill('1.25');
  await page.getByRole('button', { name: 'Lưu vận đơn nháp →' }).click();
  await expect(page.getByRole('heading', { name: reference, exact: true })).toBeVisible();
  await expect(page.getByText('Đã tạo bản nháp', { exact: true })).toBeVisible();
  const shipmentHash = new URL(page.url()).hash;
  await page.screenshot({ path: evidencePath('merchant-draft.png'), fullPage: true });
  const contextB = await browser.newContext(); const pageB = await contextB.newPage();
  await login(pageB, 'demo.merchant.b', settings.merchantBPassword);
  await expect(pageB.getByRole('heading', { name: 'Merchant B · Demo' })).toBeVisible();
  await expect(pageB.getByText(reference)).toHaveCount(0);
  await pageB.evaluate(hash => { window.location.hash = hash; }, shipmentHash);
  await expect(pageB.getByRole('alert')).toHaveText('Không tìm thấy vận đơn.');
  await contextB.close();
  await page.getByRole('textbox', { name: 'Lý do hủy' }).fill('Hủy bản nháp sau smoke test');
  await page.getByRole('button', { name: 'Hủy bản nháp', exact: true }).click();
  await expect(page.getByText('Đã hủy bản nháp', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Hủy bản nháp', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: '← Danh sách vận đơn' }).click();
  await expect(page.getByRole('link', { name: reference, exact: true })).toBeVisible();
  await expect(page.getByRole('row').filter({ hasText: reference })).toContainText('Đã hủy');
  expect(errors).toEqual([]);
});
test('invalid login retains input; admin sees overview and safe user roles', async ({ page }) => {
  await login(page, 'demo.admin', 'wrong-password');
  await expect(page.getByRole('alert')).toHaveText('Thông tin đăng nhập không hợp lệ.');
  await expect(page.getByLabel('Tên đăng nhập')).toHaveValue('demo.admin');
  await page.getByLabel('Mật khẩu', { exact: true }).fill(settings.adminPassword);
  await page.getByRole('button', { name: 'Đăng nhập →' }).click();
  await expect(page.getByRole('heading', { name: 'Tổng quan quản trị' })).toBeVisible();
  await page.screenshot({ path: evidencePath('admin-overview.png'), fullPage: true });
  await page.getByRole('link', { name: 'Tài khoản & quyền', exact: false }).first().click();
  await expect(page.getByRole('heading', { name: 'Tài khoản & quyền' })).toBeVisible();
  await expect(page.getByText('demo.disabled', { exact: true })).toBeVisible();
  await expect(page.getByText('Đã khóa', { exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Tạo bản nháp' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Đăng xuất' }).click();
  await expect(page.getByRole('heading', { name: 'Chào mừng trở lại' })).toBeVisible();
});
test('network failure retains draft form and retry uses same operation', async ({ page }) => {
  const keys: (string | undefined)[] = [];
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/demo/v1/shipments')) keys.push(request.headers()['idempotency-key']); });
  await login(page, 'demo.merchant.a', settings.merchantAPassword);
  await page.getByRole('link', { name: '＋ Tạo vận đơn nháp' }).first().click();
  await page.getByLabel('Mã tham chiếu').fill(`RETRY-${Date.now()}`);
  await page.getByLabel('Địa chỉ lấy hàng').fill('Demo pickup');
  await page.getByLabel('Tên người nhận').fill('Demo');await page.getByLabel('Số điện thoại').fill('0000000000');
  await page.getByLabel('Số nhà, đường').fill('Demo street');await page.getByLabel('Phường / xã').fill('Demo ward');
  await page.getByLabel('Tỉnh / thành phố').fill('Demo province');await page.getByLabel('Mô tả kiện hàng').fill('Demo parcel');await page.getByLabel('Khối lượng (kg)').fill('1');
  await page.route('**/api/demo/v1/shipments', route => route.request().method() === 'POST' ? route.abort() : route.continue());
  await page.getByRole('button', { name: 'Lưu vận đơn nháp →' }).click();
  await expect(page.getByRole('alert')).toContainText('Không thể kết nối backend');
  await expect(page.getByLabel('Tên người nhận')).toHaveValue('Demo');
  await page.unroute('**/api/demo/v1/shipments');
  // Explicit proxy-failure fixture: preserve form/key for a non-JSON HTTP error too.
  await page.route('**/api/demo/v1/shipments', route => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, contentType: 'text/html', body: '<h1>Synthetic upstream unavailable</h1>' }) : route.continue());
  await page.getByRole('button', { name: 'Lưu vận đơn nháp →' }).click();
  await expect(page.getByRole('alert')).toHaveText('Thao tác chưa hoàn tất. Kiểm tra backend và thử lại.');
  await expect(page.getByLabel('Tên người nhận')).toHaveValue('Demo');
  await page.unroute('**/api/demo/v1/shipments');
  await page.getByRole('button', { name: 'Lưu vận đơn nháp →' }).click();
  await expect(page.getByText('Đã tạo bản nháp', { exact: true })).toBeVisible();
  expect(keys).toHaveLength(3); expect(keys[0]).toBeTruthy(); expect(new Set(keys).size).toBe(1);
});
